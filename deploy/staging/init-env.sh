#!/usr/bin/env bash
# Staging secrets and one-time database setup. Run from deploy/staging on the VM.
#   ./init-env.sh init PUBLIC_HOST ACME_EMAIL   create .env + secrets/jwt_ed25519.pem (never overwrites, never prints)
#   ./init-env.sh roles                         create/rotate the services' Postgres login roles (after `migrate`)
#   ./init-env.sh clickhouse                    apply db/clickhouse/*.sql (idempotent)
# Secrets go to files (0600 / a 0700 directory) and through stdin or the container's environment —
# never onto a command line, where `ps` would show them.
set -euo pipefail
cd "$(dirname "$0")"
umask 077

rand() { openssl rand -hex 24; }

cmd="${1:-}"
case "$cmd" in
  init)
    host="${2:?usage: ./init-env.sh init PUBLIC_HOST ACME_EMAIL}"
    email="${3:?usage: ./init-env.sh init PUBLIC_HOST ACME_EMAIL}"
    if [ -e .env ]; then
      echo "· .env exists: left unchanged"
    else
      {
        echo "# Generated by init-env.sh on $(date -u +%FT%TZ). Never commit; back up off-box (secrets)."
        echo "VYUHA_ENV=staging"
        echo "PUBLIC_HOST=$host"
        echo "ACME_EMAIL=$email"
        echo "PG_OWNER_PASSWORD=$(rand)"
        echo "PG_GATEWAY_PASSWORD=$(rand)"
        echo "PG_ENGINE_PASSWORD=$(rand)"
        echo "PG_QUANT_PASSWORD=$(rand)"
        echo "CH_PASSWORD=$(rand)"
        echo "VYUHA_MASTER_KEY=$(openssl rand -base64 32)"
        echo "# RBI policy repo rate as a decimal and the date it was set (the admin keeps this current):"
        echo "RISK_FREE_RATE="
        echo "RISK_FREE_RATE_AS_OF="
      } > .env
      chmod 600 .env
      echo "✔ .env created (losing VYUHA_MASTER_KEY makes stored broker secrets unreadable: back it up)"
    fi
    mkdir -p secrets && chmod 700 secrets
    if [ -e secrets/jwt_ed25519.pem ]; then
      echo "· secrets/jwt_ed25519.pem exists: left unchanged"
    else
      openssl genpkey -algorithm ed25519 -out secrets/jwt_ed25519.pem
      # Readable by the gateway's non-root container user; the 0700 directory keeps other host users out.
      chmod 644 secrets/jwt_ed25519.pem
      echo "✔ secrets/jwt_ed25519.pem created"
    fi
    ;;
  roles)
    set -a; . ./.env; set +a
    # Passwords are hex (no quoting issues) and reach psql through stdin.
    { printf "\\set gateway_pw '%s'\n\\set engine_pw '%s'\n\\set quant_pw '%s'\n" \
        "$PG_GATEWAY_PASSWORD" "$PG_ENGINE_PASSWORD" "$PG_QUANT_PASSWORD"
      cat roles.sql; } | docker compose exec -T postgres psql -q -U vyuha -d vyuha -v ON_ERROR_STOP=1 -f -
    echo "✔ login roles vyuha_gateway, vyuha_engine, vyuha_quant ready"
    ;;
  clickhouse)
    for f in ../../db/clickhouse/*.sql; do
      # CLICKHOUSE_PASSWORD is already in the container's environment (compose).
      docker compose exec -T clickhouse sh -c 'clickhouse-client --user vyuha --password "$CLICKHOUSE_PASSWORD" --multiquery' < "$f"
    done
    echo "✔ ClickHouse schema applied"
    ;;
  *)
    sed -n '2,7p' "$0"
    exit 2
    ;;
esac
