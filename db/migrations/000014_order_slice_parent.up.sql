-- D-48: what a freeze-quantity slice asked for. Its children are ordinary orders that point here; the row is
-- written once, with the first child, and never changes: status and refusal reason come from the children.
-- order.parent_id stays for brackets.
CREATE TABLE order_slice_parent (
  id               uuid PRIMARY KEY,                -- the parent's id, generated by the engine
  client_order_id  text NOT NULL UNIQUE,            -- idempotency key from client
  account_id       uuid NOT NULL REFERENCES broker_account(id),
  user_id          uuid NOT NULL REFERENCES app_user(id),
  strategy_id      uuid REFERENCES strategy(id),
  source           order_source NOT NULL,
  instrument_id    bigint NOT NULL REFERENCES instrument(id),
  side             order_side NOT NULL,
  qty              int NOT NULL CHECK (qty > 0),
  order_type       order_type NOT NULL,
  product          product_type NOT NULL,
  validity         validity_type NOT NULL DEFAULT 'DAY',
  price            numeric(18,4),
  trigger_price    numeric(18,4),
  is_paper         boolean NOT NULL,
  created_at       timestamptz NOT NULL,
  CHECK (order_type NOT IN ('LIMIT','SL') OR price IS NOT NULL),
  CHECK (order_type NOT IN ('SL','SL-M') OR trigger_price IS NOT NULL)
);

ALTER TABLE "order" ADD COLUMN slice_parent_id uuid REFERENCES order_slice_parent(id);
CREATE INDEX order_slice_parent_id_idx ON "order" (slice_parent_id) WHERE slice_parent_id IS NOT NULL;

-- The blanket grants in 000001 covered only the tables that existed then. A parent row is written once and
-- never changes, so the app gets no UPDATE or DELETE.
GRANT SELECT, INSERT ON order_slice_parent TO vyuha_app;
GRANT SELECT ON order_slice_parent TO vyuha_readonly;
