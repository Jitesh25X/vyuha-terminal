constexpr vyuha::Nanos kRecv = 7;
constexpr std::int64_t kTsMs = 1'793'190'900'000;  // as in tests/upstox_test_frames.h

// Committed frames built from Upstox's schema (regenerated by vyuha_reference_tests).
std::vector<std::uint8_t> fixture(const char* name) {
  std::ifstream f(std::filesystem::path(VYUHA_FIXTURES_DIR) / "vcr" / "upstox" / name, std::ios::binary);
  return {std::istreambuf_iterator<char>(f), {}};
}

up::KeyMap keys() {
  return up::KeyMap({{"NSE_FO|61471", 101}, {"NSE_INDEX|Nifty 50", 303}, {"NSE_EQ|INE002A01018", 202}});
}

std::vector<Tick> decode(const std::vector<std::uint8_t>& frame, up::DecodeStats& stats,
                         up::FrameType* type = nullptr) {
  std::vector<Tick> out;
  const auto t =
      up::decode_frame(frame, keys(), kRecv, stats, [&out](const Tick& tick) { out.push_back(tick); });
  if (type != nullptr) {
    *type = t;
  }
  return out;
}

const Tick* by_id(const std::vector<Tick>& v, std::uint64_t id) {
  for (const auto& t : v) {
    if (t.instrument_id == id) {
      return &t;
    }
  }
  return nullptr;
}

Price rs(const char* rupees) { return *Price::parse(rupees); }

TEST(UpstoxParser, DecodesFullIndexAndLtpcFeeds) {
  up::DecodeStats stats;
  up::FrameType type{};
  const auto ticks = decode(fixture("live_feed.bin"), stats, &type);
  EXPECT_EQ(type, up::FrameType::kLiveFeed);
  ASSERT_EQ(ticks.size(), 3U);
  EXPECT_EQ(stats.malformed, 0U);

  const Tick* fut = by_id(ticks, 101);
  ASSERT_NE(fut, nullptr);
  EXPECT_EQ(fut->source, vyuha::md::Source::kUpstox);
  EXPECT_EQ(fut->ltp, rs("24450.05"));
  EXPECT_EQ(fut->prev_close, rs("24280"));
  EXPECT_EQ(fut->ltq, 75U);
  EXPECT_EQ(fut->exchange_ts, kTsMs * 1'000'000);  // ltt wins over currentTs
  EXPECT_EQ(fut->recv_ts, kRecv);
  EXPECT_EQ((std::array{fut->open, fut->high, fut->low}),
            (std::array{rs("24300"), rs("24500"), rs("24250")}));
  EXPECT_EQ(fut->avg_price, rs("24400"));
  EXPECT_EQ(fut->volume, 1'234'500U);
  EXPECT_EQ(fut->oi, 9'876'500U);
  EXPECT_EQ(fut->bid, rs("24450"));
  EXPECT_EQ(fut->ask, rs("24450.05"));
  EXPECT_EQ(fut->bid_qty, 75U);
  EXPECT_EQ(fut->bids[4].price, rs("24449.80"));  // 30 levels on the wire, best 5 kept
  EXPECT_EQ(fut->asks[4].qty, 325U);

  const Tick* idx = by_id(ticks, 303);
  ASSERT_NE(idx, nullptr);
  EXPECT_EQ(idx->ltp, rs("24400.15"));
  EXPECT_EQ(idx->low, rs("24200"));

  const Tick* eq = by_id(ticks, 202);
  ASSERT_NE(eq, nullptr);
  EXPECT_EQ(eq->ltp, rs("2450.05"));
  EXPECT_EQ(eq->exchange_ts, (kTsMs + 500) * 1'000'000);  // no ltt: frame currentTs
}

TEST(UpstoxParser, MarketInfoAndUnknownKeys) {
  up::DecodeStats stats;
  up::FrameType type{};
  EXPECT_TRUE(decode(fixture("market_info.bin"), stats, &type).empty());
  EXPECT_EQ(type, up::FrameType::kMarketInfo);
  EXPECT_EQ(stats.market_info, 1U);

  up::DecodeStats s2;
  std::vector<Tick> out;
  up::decode_frame(fixture("live_feed.bin"), up::KeyMap({{"NSE_FO|61471", 1}}), kRecv, s2,
                   [&out](const Tick& t) { out.push_back(t); });
  EXPECT_EQ(out.size(), 1U);
  EXPECT_EQ(s2.unknown_key, 2U);
}

TEST(UpstoxParser, TruncatedAndCorruptedFramesNeverOverread) {
  const auto frame = fixture("live_feed.bin");
  ASSERT_FALSE(frame.empty());
  for (std::size_t cut = 0; cut < frame.size(); ++cut) {
    up::DecodeStats stats;
    const std::vector<std::uint8_t> prefix(frame.begin(), frame.begin() + static_cast<std::ptrdiff_t>(cut));
    EXPECT_LE(decode(prefix, stats).size(), 3U);
  }
  std::mt19937 rng(1);  // NOLINT(cert-msc32-c,cert-msc51-cpp): deterministic on purpose
  for (int i = 0; i < 20'000; ++i) {
    auto mutated = frame;
    for (int k = 0; k < 3; ++k) {
      mutated[rng() % mutated.size()] = static_cast<std::uint8_t>(rng());
    }
    up::DecodeStats stats;
    const auto ticks = decode(mutated, stats);
    EXPECT_LE(ticks.size(), stats.feeds);
    for (const auto& t : ticks) {
      EXPECT_GE(t.ltp.units(), 0);  // invalid prices never escape
    }
  }
}

// F-MD-2 AC1 for Upstox: per-user limits by mode (individual / combined), plan-gated full_d30.
TEST(UpstoxSubscriptions, LimitTable) {
  const auto make = [](std::size_t n, up::Mode m, std::size_t offset = 0) {
    std::vector<up::Subscription> v;
    for (std::size_t i = 0; i < n; ++i) {
      v.push_back({"NSE_FO|" + std::to_string(offset + i), m});
    }
    return v;
  };
  const auto plan = [](const std::vector<up::Subscription>& v, up::Plan p) {
    return up::plan_subscriptions(v, p);
  };
  EXPECT_TRUE(plan(make(5000, up::Mode::kLtpc), up::Plan::kStandard).has_value());
  EXPECT_FALSE(plan(make(5001, up::Mode::kLtpc), up::Plan::kStandard).has_value());
  EXPECT_TRUE(plan(make(2000, up::Mode::kFull), up::Plan::kStandard).has_value());
  EXPECT_FALSE(plan(make(2001, up::Mode::kFull), up::Plan::kStandard).has_value());
  auto mixed = make(2001, up::Mode::kLtpc);
  mixed.push_back({"NSE_FO|x", up::Mode::kFull});
  EXPECT_FALSE(plan(mixed, up::Plan::kStandard).has_value());  // combined LTPC cap 2000
  mixed.erase(mixed.begin());
  EXPECT_TRUE(plan(mixed, up::Plan::kStandard).has_value());
  const auto d30 = make(50, up::Mode::kFullD30);
  EXPECT_EQ(plan(d30, up::Plan::kStandard).error().code, vyuha::ErrorCode::kInvalidArgument);
  EXPECT_TRUE(plan(d30, up::Plan::kPlus).has_value());
  EXPECT_EQ(plan(make(51, up::Mode::kFullD30), up::Plan::kPlus).error().code,
            vyuha::ErrorCode::kCapacityExceeded);
}

TEST(UpstoxSubscriptions, DedupesAndBuildsBinaryRequests) {
  const std::vector<up::Subscription> subs = {{"NSE_INDEX|Nifty 50", up::Mode::kLtpc},
                                              {"NSE_FO|1", up::Mode::kFull},
                                              {"NSE_INDEX|Nifty 50", up::Mode::kFull}};
  const auto planned = up::plan_subscriptions(subs, up::Plan::kStandard);
  ASSERT_TRUE(planned.has_value());
  ASSERT_EQ(planned->size(), 2U);
  EXPECT_EQ(
      up::subscribe_messages(*planned),
      std::vector<std::string>{
          R"({"guid":"vyuha-sub-1","method":"sub","data":{"mode":"full","instrumentKeys":["NSE_INDEX|Nifty 50","NSE_FO|1"]}})"});
  const std::vector<up::Subscription> odd = {{R"(A"B\C)", up::Mode::kLtpc}};
  EXPECT_EQ(up::subscribe_messages(odd).at(0),
            R"({"guid":"vyuha-sub-1","method":"sub","data":{"mode":"ltpc","instrumentKeys":["A\"B\\C"]}})");
  std::vector<up::Subscription> many;
  many.reserve(1201);
  for (int i = 0; i < 1201; ++i) {
    many.push_back({"K" + std::to_string(i), up::Mode::kLtpc});
  }
  EXPECT_EQ(up::subscribe_messages(many).size(), 3U);  // chunks of 500
}

TEST(UpstoxUrl, ParsesAuthorizedRedirect) {
  const auto u = up::parse_ws_url(
      "wss://xyz.upstox.com/market-data-feeder/v3/upstox-developer-api/feeds?requestId=r&code=c");
  ASSERT_TRUE(u.has_value());
  EXPECT_TRUE(u->tls);
  EXPECT_EQ(u->host, "xyz.upstox.com");
  EXPECT_EQ(u->port, "443");
  EXPECT_EQ(u->target, "/market-data-feeder/v3/upstox-developer-api/feeds?requestId=r&code=c");
  const auto local = up::parse_ws_url("ws://127.0.0.1:9001/f?code=1");
  ASSERT_TRUE(local.has_value());
  EXPECT_FALSE(local->tls);
  EXPECT_EQ(local->port, "9001");
  EXPECT_FALSE(up::parse_ws_url("https://x/y").has_value());
}

